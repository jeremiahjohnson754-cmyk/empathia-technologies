#!/usr/bin/env node
/**
 * The QC record of Film 13, scene 01 (docs/media/VIDEO_QA_PROCESS.md), written from measurements, never from intention.
 *   node scripts/media/film13-scene01-qc.mjs              → docs/media/film-13/SCENE_01_QC.md
 *   node scripts/media/film13-scene01-qc.mjs --check      → exit 1 if the committed record is not what the measurements say
 *   node scripts/media/film13-scene01-qc.mjs --measure    → re-measure the silent picture (.local/media/film-13/scene-01/scene-01.mp4, ffmpeg) into the record
 *   node scripts/media/film13-scene01-qc.mjs --strict     → also exit 1 when any check fails
 * Inputs: scene-01.qc.json (script, shot times, word timings heard by a transcription, picture figures) and scene-01.vtt (captions).
 */
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
import { judge, measurePicture } from './qc-lib.mjs';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'); const dir = path.join(repo, 'docs/media/film-13');
const recFile = path.join(dir, 'scene-01.qc.json'); const outFile = path.join(dir, 'SCENE_01_QC.md'); const args = process.argv.slice(2);
const rec = JSON.parse(fs.readFileSync(recFile, 'utf8')); const vtt = fs.readFileSync(path.join(dir, 'scene-01.vtt'), 'utf8');

if (args.includes('--measure')) {
  const file = path.join(repo, '.local/media/film-13/scene-01/scene-01.mp4'); const p = fs.existsSync(file) ? measurePicture(file) : null;
  if (!p) { console.error('no picture to measure (run node scripts/media/film13-scene01.mjs first; needs ffmpeg)'); process.exit(1); }
  rec.picture = p; fs.writeFileSync(recFile, JSON.stringify(rec, null, 1) + '\n'); console.log(JSON.stringify(p));
}

export const render = (r, captions) => {
  const j = judge(r, captions); const cell = (x) => String(x).replace(/\|/g, '\\|');
  const mark = { PASS: 'PASS', FAIL: '**FAIL**', 'NOT RUN': '**NOT RUN**' };
  const L = [];
  L.push(`# QC record — ${r.title}`, '');
  L.push(`Generated by \`node scripts/media/film13-scene01-qc.mjs\` from \`scene-01.qc.json\` and \`scene-01.vtt\`. Do not edit by hand. Measured ${r.measured_on}.`, '');
  L.push(`**State: ${j.verdict}.** ${j.counts.PASS} checks pass, ${j.counts.FAIL} fail, ${j.counts['NOT RUN']} could not be run. A machine cannot approve a film: APPROVED is the founder's word, after watching and listening.`, '');
  const fails = j.groups.flatMap(([g, rs]) => rs.filter((x) => x.result === 'FAIL').map((x) => `- ${x.check} (${g.toLowerCase()}): ${x.detail}.`));
  if (fails.length) L.push('## What fails', '', ...fails, '');
  L.push('## What was measured, and from what', '');
  L.push(`- Narrated master: \`${r.master.where}\` (${r.master.duration} s, ${r.master.width} × ${r.master.height}, ${r.master.streams} streams).`);
  L.push(`- Sound: ${r.master.sound_extracted}. Words and their times were heard by ${r.heard.by}.`);
  L.push(`- Picture: ${r.picture ? `the silent recording the master was made from (${r.picture.frames} frames, ${r.picture.duration} s), read with ffprobe and ffmpeg. The joined file's own picture has not been seen` : 'not measured'}.`, '');
  for (const [g, rs] of j.groups) { L.push(`## ${g}`, '', '| Check | Result | Measurement |', '|---|---|---|', ...rs.map((x) => `| ${cell(x.check)} | ${mark[x.result]} | ${cell(x.detail)} |`), ''); }
  L.push('## Where each line falls', '', '| Line | Script | Spoken (s) | Shot (s) | After the cut | Before the next |', '|---|---|---|---|---|---|');
  for (const [i, p] of j.placed.entries()) { const l = r.lines[i]; L.push(p ? `| ${l.n} | ${cell(l.text)} | ${p.from.toFixed(2)}–${p.to.toFixed(2)} | ${p.shotFrom.toFixed(2)}–${p.shotEnd.toFixed(2)} | ${(p.from - p.shotFrom).toFixed(2)} s | ${(p.shotEnd - p.to).toFixed(2)} s |` : `| ${l.n} | ${cell(l.text)} | not found | | | |`); }
  L.push('');
  if (r.history) L.push('## Earlier takes', '', ...r.history.map((h) => `- Take ${h.take}: ${h.result}${h.master ? ` (\`${h.master}\`)` : ''}`), '');
  if (r.seen) L.push('## Seen on the frames', '', `By ${r.seen.by}.`, '', ...r.seen.notes.map((n) => `- ${n}`), '');
  return { text: L.join('\n'), verdict: j.verdict, counts: j.counts };
};

if (import.meta.url === `file://${process.argv[1]}`) {
  const { text, verdict, counts } = render(rec, vtt);
  if (args.includes('--check')) { const have = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : ''; if (have !== text) { console.error('docs/media/film-13/SCENE_01_QC.md is stale: run node scripts/media/film13-scene01-qc.mjs'); process.exit(1); } }
  else fs.writeFileSync(outFile, text);
  console.log(JSON.stringify({ verdict, ...counts }));
  if (args.includes('--strict') && counts.FAIL) process.exit(1);
}
