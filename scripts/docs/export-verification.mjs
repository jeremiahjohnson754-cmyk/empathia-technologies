#!/usr/bin/env node
// Writes docs/product/COMMISSIONING_EXPORT_VERIFICATION.md from the last export check (tests/evidence/exports/EXPORT_VALIDATION.json and
// manifest.json, written by scripts/verify/export-formats.mjs): every report, the six formats, each check and its result.
//   node scripts/verify/export-formats.mjs && node scripts/docs/export-verification.mjs
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'); const ev = path.join(repo, 'tests/evidence/exports');
const v = JSON.parse(fs.readFileSync(path.join(ev, 'EXPORT_VALIDATION.json'), 'utf8')); const m = JSON.parse(fs.readFileSync(path.join(ev, 'manifest.json'), 'utf8'));
const at = fs.statSync(path.join(ev, 'EXPORT_VALIDATION.json')).mtime.toISOString().slice(0, 16).replace('T', ' ');
const fmts = ['pdf', 'docx', 'xlsx', 'csv', 'pptx', 'json'];
const byR = new Map(); for (const c of v.checks) { const k = c.report; if (!byR.has(k)) byR.set(k, []); byR.get(k).push(c); }
const kinds = [...new Set(v.checks.map((c) => `${c.format} · ${c.check}`))].sort();
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const out = [
  '# Commissioning export verification',
  '',
  `Generated by \`scripts/docs/export-verification.mjs\` from the last run of \`scripts/verify/export-formats.mjs\` (${at} UTC): **${v.passed} checks passed, ${v.failed} failed**, ${m.length} reports × ${fmts.length} formats. Every file is written by the same code the pages use, then reopened by independent readers (poppler for PDF, python-docx, openpyxl, python-pptx, the CSV and JSON parsers, LibreOffice where present); nothing is checked by the code that wrote it.`,
  '',
  '## Reports',
  '',
  '| Report | Title | Why it is in the set | Checks | Failed |',
  '|---|---|---|---|---|',
  ...m.map((r) => { const cs = byR.get(r.id) || []; return `| \`${r.id}\` | ${esc(r.title)} — ${esc(r.subtitle)} | ${esc(r.why)} | ${cs.length} | ${cs.filter((c) => !c.pass).length} |`; }),
  '',
  '## What is checked, by format',
  '',
  ...kinds.map((k) => { const cs = v.checks.filter((c) => `${c.format} · ${c.check}` === k); return `- **${esc(k)}** — ${cs.filter((c) => c.pass).length} of ${cs.length} passed`; }),
  '',
  '## Failures',
  '',
  ...(v.failed ? v.checks.filter((c) => !c.pass).map((c) => `- \`${c.report}\` ${c.format}: ${esc(c.check)} — ${esc(c.detail)}`) : ['None in this run.']),
  '',
  'Not tested in Microsoft Office itself (not available here); see `docs/exports/EXPORT_PLATFORM.md` for the platform and its known limits.',
  '',
];
fs.writeFileSync(path.join(repo, 'docs/product/COMMISSIONING_EXPORT_VERIFICATION.md'), out.join('\n'));
console.log(`wrote docs/product/COMMISSIONING_EXPORT_VERIFICATION.md (${m.length} reports, ${v.passed} passed, ${v.failed} failed)`);
