#!/usr/bin/env node
/**
 * Regenerate database/schema/schema.sql: the schema of a freshly migrated database (migrations 0001…N, no data), as pg_dump prints it,
 * with ownership statements and pg_dump's per-run \restrict keys removed so the file is reproducible and diff-friendly.
 * The migrations in database/migrations/ remain the source of truth; this file is a reading copy.
 *   node scripts/docs/dump-schema.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { freshDb, repo } from './_db.mjs';

const db = await freshDb('empathia_doc_schema');
try {
  const raw = db.dump(['--schema-only', '--no-owner', '--schema=app', '--schema=app_meta']);
  const body = raw.split('\n')
    .filter((l) => !/^\\(un)?restrict /.test(l) && !/^-- Dumped (from|by) /.test(l))
    .join('\n').replace(/\n{3,}/g, '\n\n');
  const migrations = fs.readdirSync(path.join(repo, 'database/migrations')).filter((f) => f.endsWith('.sql')).sort();
  const head = `-- GENERATED by scripts/docs/dump-schema.mjs — do not edit. Source of truth: database/migrations/ (${migrations.join(', ')}).\n-- Schema of a freshly migrated database (schemas app and app_meta), pg_dump --schema-only --no-owner, PostgreSQL 16.\n`;
  const out = head + body.trimEnd() + '\n';
  const file = path.join(repo, 'database/schema/schema.sql');
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(file) && fs.readFileSync(file, 'utf8') === out;
    console.log(same ? 'PASS: database/schema/schema.sql matches the migrations' : 'FAIL: database/schema/schema.sql is stale — run node scripts/docs/dump-schema.mjs');
    process.exitCode = same ? 0 : 1;
  } else {
    fs.writeFileSync(file, out);
    console.log(`wrote database/schema/schema.sql (${out.split('\n').length} lines, ${migrations.length} migrations)`);
  }
} finally { db.drop(); }
