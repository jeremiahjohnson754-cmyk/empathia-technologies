#!/usr/bin/env node
/**
 * Generated architecture diagrams — produced FROM the source, so they cannot drift from it.
 *   node scripts/docs/diagrams.mjs            writes docs/architecture/diagrams/1x-*.mmd (+ .svg when the Mermaid CLI is installed)
 *   node scripts/docs/diagrams.mjs --check    regenerates in memory and fails if a committed .mmd differs (wired into scripts/build.mjs)
 *
 * Sources (built dist): @empathia/project-governance (governance + delivery machines, reopen rule, execution states),
 * @empathia/service-engine (service machine), @empathia/field-intelligence (FIPV states/exits/adapters, edges asserted by driving the
 * engine), @empathia/event-contracts (the 1.0.0 event names), the workspace package.json files (the dependency graph).
 * Hand-drawn diagrams 01–09 in the same folder are not touched.
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = path.join(root, 'docs/architecture/diagrams');
const check = process.argv.includes('--check');
const imp = (p) => import(path.join(root, p));
const gov = await imp('packages/project-governance/dist/src/index.js');
const svc = await imp('packages/service-engine/dist/src/index.js');
const fi = await imp('packages/field-intelligence/dist/src/index.js');
const ev = await imp('packages/event-contracts/dist/src/index.js');
const head = (title, source) => `%% GENERATED by scripts/docs/diagrams.mjs from ${source} — do not edit; regenerate (the build checks for drift).\n%% ${title}\n`;
const esc = (s) => String(s).replace(/"/g, '#quot;').replace(/;/g, ',').replace(/:/g, ' -');   // ';' and ':' are grammar in stateDiagram labels
const machine = (title, source, states, transitions, extras = []) => {
  const lines = ['stateDiagram-v2', `  direction LR`];
  for (const t of transitions) lines.push(`  ${t.from} --> ${t.to}: ${esc(t.authority)}<br/>guard ${esc(t.guard)}`);
  for (const x of extras) lines.push(`  ${x}`);
  const terminal = states.filter((s) => !transitions.some((t) => t.from === s) && !extras.some((x) => x.startsWith(`${s} -->`)));
  for (const s of terminal) lines.push(`  ${s} --> [*]`);
  const initial = states.filter((s) => !transitions.some((t) => t.to === s) && !extras.some((x) => x.includes(`--> ${s}`)));
  for (const s of initial) lines.unshift(`  [*] --> ${s}`);
  lines.splice(2, 0, ...lines.splice(0, initial.length));   // keep the [*] entries after the header
  return head(title, source) + lines.join('\n') + '\n';
};

const diagrams = {};

// 10 — governance machine (verbatim transitions incl. the reopen rule)
diagrams['10-governance-state-machine.mmd'] = machine(
  'Project governance: the request from draft to funded, with hold/reject/suspend and reopening (ADR-0008).', 'packages/project-governance (GOVERNANCE_TRANSITIONS, REOPEN_FROM)',
  gov.GOVERNANCE_STATES, gov.GOVERNANCE_TRANSITIONS,
  gov.REOPEN_FROM.map((s) => `${s} --> INTERNAL_ROUTE_RECORDED: scope.revise (reopen)<br/>guard new_scope_revision`));

// 11 — delivery machine with the two authorizations
diagrams['11-delivery-state-machine.mmd'] = (() => {
  const t = gov.DELIVERY_TRANSITIONS; const exec = new Set(gov.EXECUTION_STATES);
  const lines = [head('Project delivery: concept authorization opens preliminary design; execution authorization (funding + domain approvals) opens the release for construction and everything after it (ADR-0008 decision 2).', 'packages/project-governance (DELIVERY_TRANSITIONS, EXECUTION_STATES)'), 'stateDiagram-v2', '  direction TB', `  [*] --> ${gov.DELIVERY_STATES[0]}`];
  lines.push('  state "Concept work — authorized by an approved brief, before funding" as Concept {');
  for (const s of gov.DELIVERY_STATES.filter((s) => !exec.has(s))) lines.push(`    ${s}`);
  lines.push('  }', '  state "Execution — requires FUNDED and the domain approvals" as Execution {');
  for (const s of gov.DELIVERY_STATES.filter((s) => exec.has(s))) lines.push(`    ${s}`);
  lines.push('  }');
  for (const x of t) lines.push(`  ${x.from} --> ${x.to}: ${esc(x.authority)}<br/>guard ${esc(x.guard)}`);
  lines.push(`  ${gov.DELIVERY_STATES[gov.DELIVERY_STATES.length - 1]} --> [*]`);
  return lines.join('\n') + '\n';
})();

// 12 — service machine
diagrams['12-service-state-machine.mmd'] = machine('ServiceHands: a work order from open to closed; reopening and cancellation.', 'packages/service-engine (SERVICE_TRANSITIONS)', svc.SERVICE_STATES, svc.SERVICE_TRANSITIONS);

// 13 — Field Intelligence v1.4 session: edges asserted against the engine, not transcribed
diagrams['13-field-intelligence-session.mmd'] = (() => {
  const now = '2026-10-31T10:00:00.000Z';
  const actor = (persona, auth) => ({ persona, now, can: (a) => [].concat(a).some((x) => auth.includes(x)) });
  const syseng = actor('syseng', ['protocol.approve', 'plan.compile', 'test.verify']), ops = actor('opslead', ['window.approve']), tech = actor('service', ['work.accept', 'work.evidence']), cx = actor('cxeng', ['tests.verify.all', 'test.verify', 'fipv.review']);
  const S = (r) => { if (fi.isRefusal(r)) throw new Error(r.why.join('; ')); return 'session' in r ? r.session : r; };
  const fresh = () => fi.createSession('FIS-D', 'R-1', 'BRD', [{ id: 'TP-1', label: 'seat 1' }, { id: 'TP-2', label: 'seat 4' }], [{ id: 'LAEQ', label: 'LAeq', adapter: 'ADP-SLM' }, { id: 'CAM-FOV', label: 'cam', adapter: 'ADP-CAM' }], syseng);
  const edges = []; const edge = (from, to, label) => edges.push([from, to, label]);
  const expect = (from, s, to, label) => { if (s.state !== to) throw new Error(`diagram edge ${from} → ${to} (${label}) is not what the engine does: ${s.state}`); edge(from, to, label); };
  let s = fresh(); expect('DRAFT', s, 'DRAFT', 'proposal');
  expect('DRAFT', S(fi.eligibility(fresh(), syseng, false)), 'NOT_LICENSED', 'no site licence');
  expect('DRAFT', S(fi.eligibility(fi.createSession('FIS-E', 'R-1', 'BRD', [], [{ id: 'CAM-FOV', label: 'x', adapter: 'ADP-CAM' }], syseng), syseng, true)), 'NOT_SUPPORTED', 'only NOT_CONFIGURED adapters');
  s = S(fi.eligibility(fresh(), syseng, true)); expect('DRAFT', s, 'SAFETY_PREFLIGHT', 'licensed, eligible tests');
  s = S(fi.preflight(s, syseng, { step: 'protocol', levelLimit: 85 }));
  expect('SAFETY_PREFLIGHT', S(fi.preflight(s, ops, { step: 'window', occupied: true, privacyNotice: true })), 'OCCUPIED', 'window occupied');
  s = S(fi.preflight(s, ops, { step: 'window', occupied: false, privacyNotice: true }));
  expect('SAFETY_PREFLIGHT', S(fi.preflight(s, tech, { step: 'operator', present: false, qualified: true })), 'AWAITING_CONSENT', 'operator absent');
  s = S(fi.preflight(s, tech, { step: 'operator', present: true, qualified: true }));
  expect('SAFETY_PREFLIGHT', S(fi.preflight(s, tech, { step: 'instrument', instrument: { model: 'm', serial: 's', calibrationId: 'c', calibrationDue: '2026-01-01' } })), 'OUT_OF_CALIBRATION', 'calibration past due');
  s = S(fi.preflight(s, tech, { step: 'instrument', instrument: { model: 'm', serial: 's', calibrationId: 'c', calibrationDue: '2027-01-01' } }));
  expect('SAFETY_PREFLIGHT', S(fi.preflight(s, tech, { step: 'estop', verified: false })), 'PRECONDITION_FAILED', 'E-stop unverified');
  s = S(fi.preflight(s, tech, { step: 'estop', verified: true })); expect('SAFETY_PREFLIGHT', s, 'DRY_RUN', 'five approvals by different authorities');
  s = S(fi.dryRun(s, tech)); expect('DRY_RUN', s, 'APPROVAL_PENDING', 'dry run emits nothing');
  s = S(fi.authorize(s, cx, true)); expect('APPROVAL_PENDING', s, 'APPROVAL_PENDING', 'commissioning lead authorizes (recorded on the session; arming is the next step)');
  expect('APPROVAL_PENDING', S(fi.arm(s, tech, true, true, false)), 'NOT_CONFIGURED', 'real build: no validated driver');
  s = S(fi.arm(s, tech, true, true)); expect('APPROVAL_PENDING', s, 'ARMED', 'authorized; two confirmations by the consenting operator (simulation)');
  const r1 = S(fi.run(s, tech)); expect('ARMED', r1, 'RUNNING', 'first point');
  expect('RUNNING', S(fi.run(r1, tech)), 'ACQUIRED', 'last point, restore verified');
  expect('RUNNING', S(fi.run(r1, tech, 'excessive_level')), 'ABORTED', 'level above the protocol limit');
  expect('RUNNING', S(fi.run(r1, tech, 'occupied')), 'OCCUPIED', 'room became occupied');
  expect('RUNNING', S(fi.estop(r1, tech)), 'ABORTED', 'E-stop');
  const lines = [head('Field Intelligence v1.4 (Physical Validation) session: every edge below was produced by driving @empathia/field-intelligence while generating this file.', 'packages/field-intelligence (createSession, eligibility, preflight, dryRun, authorize, arm, run, estop)'), 'stateDiagram-v2', '  direction LR', '  [*] --> DRAFT'];
  const merged = new Map();   // one arrow per (from, to); every cause that produced it is on the label
  for (const [a, b, l] of edges) { if (a === b) continue; const k = `${a}>${b}`; merged.set(k, [...(merged.get(k) || []), l]); }
  for (const [k, ls] of merged) { const [a, b] = k.split('>'); lines.push(`  ${a} --> ${b}: ${esc(ls.join(' / '))}`); }
  for (const x of fi.FIPV.exits) if (edges.some(([, b]) => b === x)) lines.push(`  ${x} --> [*]`);
  lines.push('  ACQUIRED --> [*]');
  lines.push(`  note right of ARMED\n    adapters: ${fi.FIPV.adapters.map((a) => `${a.id} ${a.tier}`).join(', ')}\n  end note`);
  return lines.join('\n') + '\n';
})();

// 14 — event flow: the 1.0.0 contract names grouped by aggregate, through the outbox to the consumers that exist in code
diagrams['14-event-flow.mmd'] = (() => {
  const names = Object.keys(ev.EVENT_CONTRACTS); const groups = {};
  for (const n of names) { const g = n.split('.')[0]; (groups[g] ||= []).push(n); }
  const lines = [head(`Event flow: ${names.length} event types (schema ${ev.EVENT_SCHEMA_VERSION}) validated at emit time, appended in the same transaction as the change, delivered by the outbox worker.`, 'packages/event-contracts (EVENT_CONTRACTS) and services/enterprise-api/src/worker/outbox.ts'), 'flowchart LR'];
  lines.push('  API[enterprise-api<br/>RequestContext.emit validates the payload<br/>against the contract] -->|same transaction| OUTBOX[(app.outbox_event)]');
  lines.push('  OUTBOX -->|poll · retries · dead letter| WORKER[outbox worker]');
  lines.push('  WORKER --> RM[(read models)]', '  WORKER --> NOTIF[(notifications)]', '  WORKER -.->|planned| INTEG[integration adapters]');
  lines.push('  subgraph Contracts["Event types by aggregate (count)"]');
  for (const [g, list] of Object.entries(groups).sort()) lines.push(`    ${g.replace(/[^a-z0-9]/gi, '_')}["${g} (${list.length})<br/>${list.map((n) => n.slice(g.length + 1)).join('<br/>')}"]`);
  lines.push('  end', '  Contracts -.-> API');
  return lines.join('\n') + '\n';
})();

// 15 — the dependency graph of the workspace packages (from package.json)
diagrams['15-package-graph.mmd'] = (() => {
  const dirs = ['packages', 'services', 'apps', 'integrations'].flatMap((d) => fs.readdirSync(path.join(root, d)).map((n) => path.join(d, n))).filter((p) => fs.existsSync(path.join(root, p, 'package.json')));
  const pk = dirs.map((p) => ({ dir: p, ...JSON.parse(fs.readFileSync(path.join(root, p, 'package.json'), 'utf8')) })).filter((p) => p.name?.startsWith('@empathia/'));
  const id = (n) => n.replace('@empathia/', '').replace(/[^a-z0-9]/gi, '_');
  const lines = [head('Workspace dependency graph: every @empathia/* dependency declared in a package.json (apps also bundle a few packages from source — those aliases are listed in each app’s build.mjs).', 'package.json of packages/*, services/*, apps/*, integrations/*'), 'flowchart TB'];
  for (const d of ['apps', 'services', 'integrations', 'packages']) {
    lines.push(`  subgraph ${d}`);
    for (const p of pk.filter((x) => x.dir.startsWith(d + '/'))) lines.push(`    ${id(p.name)}["${p.name.replace('@empathia/', '')}"]`);
    lines.push('  end');
  }
  for (const p of pk) for (const dep of Object.keys({ ...(p.dependencies || {}), ...(p.devDependencies || {}) })) if (dep.startsWith('@empathia/')) lines.push(`  ${id(p.name)} --> ${id(dep)}`);
  return lines.join('\n') + '\n';
})();

// ---- write or check
let drift = 0;
for (const [name, text] of Object.entries(diagrams)) {
  const f = path.join(outDir, name);
  if (check) { const cur = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : ''; if (cur !== text) { drift += 1; console.error(`DRIFT ${name}: regenerate with node scripts/docs/diagrams.mjs`); } continue; }
  fs.writeFileSync(f, text);
  const mmdc = spawnSync('mmdc', ['-i', f, '-o', f.replace(/\.mmd$/, '.svg'), '-b', 'transparent', '-q'], { encoding: 'utf8' });
  console.log(`${name}${mmdc.status === 0 ? ' + svg' : mmdc.error ? ' (mmdc not installed: no svg)' : ` (mmdc failed: ${(mmdc.stderr || '').split('\n')[0]})`}`);
}
if (check) { if (drift) process.exit(1); console.log(`diagrams: ${Object.keys(diagrams).length} generated diagrams match the source`); }
