#!/usr/bin/env node
// Writes docs/product/COMMISSIONING_TEST_CATALOG.md from the engine's own data (packages/domain-data: V25_TESTS — the base library — and
// V25_CX_CATALOGUE — the discipline packs), so the catalogue a reader sees is the one the engine applies. Run after the data changes:
//   node scripts/docs/test-catalog.mjs
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const J = (f) => JSON.parse(fs.readFileSync(path.join(repo, 'packages/domain-data/data', f), 'utf8'));
const base = J('V25_TESTS.json'); const packs = J('V25_CX_CATALOGUE.json'); const labels = J('V25_TEST_LABEL.json'); const phases = J('V25_PHASES.json');
const phaseName = (n) => { const p = phases.find((x) => x[0] === n); return p ? p[1] : String(n); };   // V25_PHASES: [n, name, what it covers]
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const yes = (b) => (b ? 'yes' : '—');
const row = (id, t, label) => `| \`${id}\` | ${esc(label)} | ${esc(t.domain)} | ${t.phase} | ${t.tier} | ${esc(t.verifier)} | ${esc((t.accepts || []).join(', '))} | ${t.nonwaivable ? '**no**' : 'yes'} | ${yes(t.na)} | ${yes(t.instrument)} | ${esc(t.method)} |`;
const head = '| Test | Label | Domain | Phase | Tier | Verified by | Evidence accepted | Waivable | May be N/A | Instrument | Method |\n|---|---|---|---|---|---|---|---|---|---|---|';
const bePhase = (rows) => [...rows].sort((a, b) => a[1].phase - b[1].phase || a[1].tier - b[1].tier || a[0].localeCompare(b[0]));
const baseRows = bePhase(Object.entries(base)); const packRows = Object.entries(packs);
const byPack = {}; for (const [id, t] of packRows) (byPack[t.pack] ||= []).push([id, t]);
const nonwaivable = [...baseRows, ...packRows].filter(([, t]) => t.nonwaivable).map(([id]) => `\`${id}\``);
const out = [
  '# Commissioning test catalogue',
  '',
  `Generated by \`scripts/docs/test-catalog.mjs\` from the engine's data (\`packages/domain-data\`); do not edit by hand. ${baseRows.length} base tests and ${packRows.length} discipline-pack tests in ${Object.keys(byPack).length} packs.`,
  '',
  'Which tests apply to a room is decided by the engine (`packages/commissioning-engine/src/applicability.ts`) from the room\'s archetype, devices, tier and risk; each applicable row on a room states why it applies. **Waivable: no** means no exception, waiver or deferral may carry a failure of that test (safety, security, evidence integrity and separation of duties are among them). Methods describe the field practice in the product\'s own words; no standard is reproduced.',
  '',
  `Phases (the engine's names; the demonstration's room pages show them as Readiness, Physical QA, Infrastructure and platform, Functional, Operational and experience): ${phases.map((x) => `${x[0]} ${x[1]}`).join(' · ')}; sign-off follows.`,
  '',
  '## Base library',
  '',
  head, ...baseRows.map(([id, t]) => row(id, t, labels[id] || id)),
  '',
  '## Discipline packs',
  '',
  ...Object.entries(byPack).flatMap(([p, rs]) => [`### ${p} (${rs.length})`, '', head, ...bePhase(rs).map(([id, t]) => row(id, t, t.label || labels[id] || id)), '']),
  '## Not open to exception',
  '',
  `${nonwaivable.length} tests: ${nonwaivable.join(', ')}.`,
  '',
];
fs.writeFileSync(path.join(repo, 'docs/product/COMMISSIONING_TEST_CATALOG.md'), out.join('\n'));
console.log(`wrote docs/product/COMMISSIONING_TEST_CATALOG.md (${baseRows.length} base + ${packRows.length} pack tests, ${nonwaivable.length} not waivable)`);
