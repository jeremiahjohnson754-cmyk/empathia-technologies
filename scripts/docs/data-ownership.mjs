#!/usr/bin/env node
/**
 * Generate docs/database/DATA_OWNERSHIP.md: which source module writes (INSERT / UPDATE / DELETE) which table, found by scanning the
 * SQL statements in services/enterprise-api/src and services/integration-worker. Reads are not listed (every module reads broadly
 * inside its tenant). A table written by several modules is flagged so ownership can be tightened.
 *   node scripts/docs/data-ownership.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const roots = ['services/enterprise-api/src', 'services/integration-worker'];
const files = [];
const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (/\.(ts|mjs)$/.test(e.name)) files.push(p); } };
for (const r of roots) walk(path.join(repo, r));
const writes = new Map();   // table → Map(file → Set(ops))
for (const f of files) {
  const s = fs.readFileSync(f, 'utf8');
  for (const m of s.matchAll(/\b(INSERT INTO|UPDATE|DELETE FROM|TRUNCATE)\s+app\.(\w+)/g)) {
    const op = m[1].split(' ')[0]; const t = m[2];
    const rel = path.relative(repo, f);
    if (!writes.has(t)) writes.set(t, new Map());
    const by = writes.get(t); if (!by.has(rel)) by.set(rel, new Set()); by.get(rel).add(op);
  }
}
const md = ['# Data ownership — who writes which table', '', 'GENERATED by `scripts/docs/data-ownership.mjs` from the SQL in `services/enterprise-api/src` and `services/integration-worker`. Do not edit by hand.', '',
  'Migrations (`database/migrations/`) and the synthetic seed (`src/db/seed.ts`) are listed too: the seed writes catalogue and identity tables as the schema owner. Append-only tables (audit, evidence, results, verifications, revisions, issue events) are only ever INSERTed.', '',
  '| Table | Written by (operations) | Writers |', '|---|---|---|'];
for (const t of [...writes.keys()].sort()) {
  const by = writes.get(t);
  md.push(`| \`app.${t}\` | ${[...by].map(([f, ops]) => `\`${f.replace('services/enterprise-api/src/', 'api/')}\` (${[...ops].join(', ')})`).join('<br>')} | ${by.size}${by.size > 2 ? ' ⚑' : ''} |`);
}
md.push('', '⚑ more than two writing modules: a candidate for routing writes through one domain module.', '');
fs.writeFileSync(path.join(repo, 'docs/database/DATA_OWNERSHIP.md'), md.join('\n'));
console.log(`wrote docs/database/DATA_OWNERSHIP.md (${writes.size} tables written by ${files.length} scanned files)`);
