#!/usr/bin/env python3
"""Write apps/demo/src/signal/takes-s01.ts from the Season 1 take maps (media/signal/s01/<group>.take.json) and the split files that
exist (apps/demo/public/media/signal/s01/<group>-<n>.mp3): one Take per line, under its chapter. A take not yet provided is skipped,
so its lines stay captions.   python3 -I media/signal/s01/build-takes.py"""
import glob, json, os
root = os.path.dirname(os.path.abspath(__file__)); repo = os.path.abspath(os.path.join(root, '../../..'))
pub = os.path.join(repo, 'apps/demo/public'); out = {}
for f in sorted(glob.glob(os.path.join(root, '*.take.json'))):
    g = os.path.basename(f)[:-len('.take.json')]; who = g.split('-')[0]; t = json.load(open(f, encoding='utf8'))
    for k, (ch, line) in enumerate(zip(t['chapters'], t['lines']), 1):
        src = f'media/signal/s01/{g}-{k}.mp3'
        if os.path.exists(os.path.join(pub, src)): out.setdefault(ch, []).append({'who': who, 'text': line, 'src': src})
# single-line takes (auditions chosen by the founder that speak a canon line): media/signal/s01/singles.json
sp = os.path.join(root, 'singles.json')
if os.path.exists(sp):
    for s in json.load(open(sp, encoding='utf8')):
        if os.path.exists(os.path.join(pub, s['src'])): out.setdefault(s['chapter'], []).append({'who': s['who'], 'text': s['text'], 'src': s['src']})
# generated footage (media/signal/s01/film/shots.tsv), placed before the canon item it sets up; only files that exist are listed
foot = {}
for row in open(os.path.join(root, 'film/shots.tsv'), encoding='utf8').read().splitlines()[1:]:
    ch, before, slot, _job, note = row.split('\t')
    src = f'media/signal/s01/film/{ch}-{slot}.mp4'
    if os.path.exists(os.path.join(pub, src)): foot.setdefault(ch, []).append({'before': int(before), 'src': src, 'note': note + ' Generated footage of the setting, not a real venue or real people.'})
fbody = ',\n'.join(f'  {ch}: [\n' + ',\n'.join('    ' + json.dumps(x, ensure_ascii=False) for x in xs) + ',\n  ]' for ch, xs in sorted(foot.items()))
body = ',\n'.join(f'  {ch}: [\n' + ',\n'.join('    ' + json.dumps(x, ensure_ascii=False) for x in xs) + ',\n  ]' for ch, xs in sorted(out.items()))
ts = ('/** Season 1 takes, generated by media/signal/s01/build-takes.py from the take maps and the split files; do not edit by hand. */\n'
      "import type { Take, Footage } from './cinematic.js';\n\nexport const TAKES_S01: Record<string, Take[]> = {\n" + body + ('\n' if body else '') + '};\n'
      + "\nexport const FOOTAGE_S01: Record<string, Footage[]> = {\n" + fbody + ('\n' if fbody else '') + '};\n')
open(os.path.join(repo, 'apps/demo/src/signal/takes-s01.ts'), 'w', encoding='utf8').write(ts)
print({ch: len(xs) for ch, xs in sorted(out.items())}, sum(len(x) for x in out.values()), 'footage', sum(len(x) for x in foot.values()))
