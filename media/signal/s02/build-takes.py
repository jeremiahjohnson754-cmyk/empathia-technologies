#!/usr/bin/env python3
"""Write apps/demo/src/signal/takes-s02.ts from the Season 2 line list (media/signal/s02/lines.json: id, chapter, who, text, voice) and
the takes that exist (apps/demo/public/media/signal/s02/<id>.mp3), one Take per line under its chapter; a line without its file stays a
caption. Season 2's voices are Qwen3-TTS presets chosen by the founder (19 Nov 2026 17:54: Maya = Vivian, Ben = Aiden; the rest cast
from the same presets), generated on this machine with the CustomVoice model; no voice is cloned from anyone.
   python3 -I media/signal/s02/build-takes.py"""
import json, os
root = os.path.dirname(os.path.abspath(__file__)); repo = os.path.abspath(os.path.join(root, '../../..'))
pub = os.path.join(repo, 'apps/demo/public'); lines = json.load(open(os.path.join(root, 'lines.json'), encoding='utf8'))
out = {}; voices = {}
for l in lines:
    src = f"media/signal/s02/{l['id']}.mp3"
    if not os.path.exists(os.path.join(pub, src)): continue
    out.setdefault(l['chapter'], []).append({'who': l['who'], 'text': l['text'], 'src': src})
    voices[l['who']] = 'Qwen3-TTS ' + l['voice'].replace('_', ' ').title() + ' (AI voice)'
body = ',\n'.join(f'  {ch}: [\n' + ',\n'.join('    ' + json.dumps(x, ensure_ascii=False) for x in xs) + ',\n  ]' for ch, xs in sorted(out.items()))
vb = ', '.join(f'{json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}' for k, v in sorted(voices.items()))
ts = ('/** Season 2 takes, generated by media/signal/s02/build-takes.py from the line list and the files; do not edit by hand. */\n'
      "import type { Take } from './cinematic.js';\n\nexport const TAKES_S02: Record<string, Take[]> = {\n" + body + ('\n' if body else '') + '};\n'
      + '/** The AI voice heard for each Season 2 speaker (a Qwen3-TTS preset; not a person, not a clone). */\n'
      + 'export const VOICES_S02: Record<string, string> = { ' + vb + ' };\n')
open(os.path.join(repo, 'apps/demo/src/signal/takes-s02.ts'), 'w', encoding='utf8').write(ts)
print({ch: len(xs) for ch, xs in sorted(out.items())}, sum(len(x) for x in out.values()), 'voices', len(voices))
