/**
 * Generate the typed API client from the OpenAPI document. Request bodies, path parameters and query parameters are typed from the
 * contract; responses are typed where the route table declares a response schema and otherwise as the hand-written types in
 * src/types.ts (mapped by operationId), falling back to `unknown`.
 */
const ident = (s) => s.replace(/[^A-Za-z0-9_]/g, '_');
function tsType(s, indent = '') {
  if (!s) return 'unknown';
  let t;
  if (s.enum) t = s.enum.map((v) => JSON.stringify(v)).join(' | ');
  else {
    const ty = Array.isArray(s.type) ? s.type.find((x) => x !== 'null') : s.type;
    if (ty === 'object') {
      const req = new Set(s.required || []);
      const props = Object.entries(s.properties || {}).map(([k, v]) => `${indent}  ${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}${req.has(k) ? '' : '?'}: ${tsType(v, indent + '  ')};`);
      t = props.length ? `{\n${props.join('\n')}\n${indent}}` : 'Record<string, unknown>';
    } else if (ty === 'array') t = `Array<${tsType(s.items, indent)}>`;
    else if (ty === 'integer' || ty === 'number') t = 'number';
    else if (ty === 'boolean') t = 'boolean';
    else if (ty === 'string') t = 'string';
    else t = 'unknown';
  }
  const nullable = Array.isArray(s.type) && s.type.includes('null');
  return nullable ? `${t} | null` : t;
}

export function generateClient(doc) {
  const ops = [];
  for (const [p, methods] of Object.entries(doc.paths)) for (const [m, op] of Object.entries(methods)) ops.push({ path: p, method: m.toUpperCase(), op });
  ops.sort((a, b) => a.op.operationId.localeCompare(b.op.operationId));
  const lines = [];
  lines.push('/* eslint-disable */');
  lines.push('// GENERATED by scripts/api/export-openapi.mjs from the enterprise API route table — do not edit by hand.');
  lines.push(`// ${doc.info.title} ${doc.info.version}: ${ops.length} operations.`);
  lines.push("import type { ResponseTypes } from './types.js';");
  lines.push('');
  lines.push('/** The hand-written response type of an operation, or unknown when none is declared. */');
  lines.push('type R<K extends string> = K extends keyof ResponseTypes ? ResponseTypes[K] : unknown;');
  lines.push('');
  lines.push('export interface Operations {');
  for (const { path, method, op } of ops) {
    const pathParams = (op.parameters || []).filter((x) => x.in === 'path').map((x) => x.name);
    const query = (op.parameters || []).filter((x) => x.in === 'query');
    const body = op.requestBody?.content?.['application/json']?.schema;
    const binary = !!op.requestBody?.content?.['application/octet-stream'];
    const okCode = Object.keys(op.responses).find((c) => Number(c) < 300);
    const okSchema = op.responses[okCode]?.content?.['application/json']?.schema;
    lines.push(`  /** ${method} ${path} — ${op.summary}${op['x-authority'] ? ` (authority: ${[].concat(op['x-authority']).join(' | ')})` : ''} */`);
    lines.push(`  ${ident(op.operationId)}: {`);
    lines.push(`    method: '${method}'; path: '${path}'; auth: ${op.security.length > 0}; idempotent: ${(op.parameters || []).some((x) => x.name === 'Idempotency-Key')};`);
    lines.push(`    params: { ${pathParams.map((n) => `${n}: string`).join('; ')}${pathParams.length ? ' ' : ''}};`);
    lines.push(`    query: { ${query.map((q) => `${q.name}?: ${tsType(q.schema)}`).join('; ')}${query.length ? ' ' : ''}};`);
    lines.push(`    body: ${binary ? 'Blob | ArrayBuffer | Uint8Array' : body ? tsType(body, '    ') : 'undefined'};`);
    lines.push(`    response: ${okSchema ? tsType(okSchema, '    ') : `R<'${ident(op.operationId)}'>`};`);
    lines.push('  };');
  }
  lines.push('}');
  lines.push('');
  lines.push('export const OPERATIONS = {');
  for (const { path, method, op } of ops) lines.push(`  ${ident(op.operationId)}: { method: '${method}', path: '${path}', auth: ${op.security.length > 0} },`);
  lines.push('} as const;');
  lines.push('');
  return lines.join('\n');
}
