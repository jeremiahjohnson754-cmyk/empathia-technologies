#!/usr/bin/env node
/**
 * tokens.json → dist/tokens.css (CSS custom properties), dist/tokens.js + .d.ts (typed constants), dist/fonts.css + dist/fonts/
 * (self-hosted Inter, copied from fonts/), and dist/theme-init.js (the no-flash theme script every surface loads in <head>).
 *
 * Theme contract (D9, D36):
 *   - bare :root = Graphite (dark);
 *   - the system's light preference gives Paper unless the page says data-theme="dark";
 *   - data-theme="light" | "dark" on ANY element applies that theme to the element and its subtree, so an explicit choice always wins
 *     and a panel can carry the other theme;
 *   - data-stage on an element keeps it Graphite whatever the page theme (spatial stages stay dark in light mode, D36).
 * The theme choice (System / Light / Dark) is stored under localStorage "empathia.theme" (packages/ui/src/theme.tsx); theme-init.js
 * applies it to <html> before first paint. "system" or nothing stored = no attribute = follow the system.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const T = JSON.parse(fs.readFileSync(path.join(here, 'tokens.json'), 'utf8'));
const dist = path.join(here, 'dist');
const own = (o) => Object.entries(o).filter(([k]) => !k.startsWith('$'));
export const STORAGE_KEY = 'empathia.theme';

// text on a product-colour fill: whichever of the theme's darkest ink or white reads better
const lum = (h) => { const c = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4)); return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]; };
const ratio = (a, b) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };
const inkOn = (fill) => (ratio(fill, '#ffffff') >= ratio(fill, '#0e1012') ? '#ffffff' : '#0e1012');

const varsFor = (mode, indent = '  ') => [
  ...own(T.color).map(([k, v]) => `--${k}: ${v[mode]};`),
  ...own(T.product).flatMap(([k, v]) => [`--p-${k}: ${v[mode]};`, `--p-${k}-ink: ${inkOn(v[mode])};`]),
  ...own(T.class).map(([k, v]) => `--c-${k}: ${v[mode]};`),
  ...own(T.evidence).map(([k, v]) => `--ev-${k.toLowerCase().replace(/_/g, '-')}: ${v[mode]};`),
  `--shadow: ${T.shadow[mode]};`,
  `--theme-name: "${T.theme[mode].name}";`,
  `color-scheme: ${mode};`,
].map((l) => indent + l).join('\n');
const fixed = [
  ...own(T.font).map(([k, v]) => `--font-${k}: ${v};`),
  ...own(T.type).map(([k, v]) => `--fs-${k}: ${v};`),
  ...own(T.tracking).map(([k, v]) => `--track-${k}: ${v};`),
  ...own(T.space).map(([k, v]) => `--sp-${k}: ${v};`),
  ...own(T.radius).map(([k, v]) => `--r-${k}: ${v};`),
  `--target-min: ${T.target.min};`,
  `--ease: ${T.motion.ease};`, `--t-fast: ${T.motion.fast};`, `--t-med: ${T.motion.med};`, `--t-slow: ${T.motion.slow};`,
].map((l) => '  ' + l).join('\n');

const css = `/* GENERATED by packages/design-tokens/build-tokens.mjs from tokens.json — do not edit by hand.
   Graphite (dark) by default; Paper (light) when the system prefers light; data-theme="light"|"dark" on any element always wins;
   data-stage keeps a spatial stage Graphite in either theme (D36). Teal (--accent) is the interaction accent only (D8). */
:root {
${fixed}
${varsFor('dark')}
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
${varsFor('light', '    ')}
  }
}
[data-theme="light"] {
${varsFor('light')}
}
[data-theme="dark"], [data-stage] {
${varsFor('dark')}
}
@media (prefers-reduced-motion: reduce) {
  :root { --t-fast: 0ms; --t-med: 0ms; --t-slow: 0ms; }
}
/* Breakpoints (for reference in media queries): ${own(T.breakpoint).map(([k, v]) => `${k} ${v}`).join(', ')} */
`;

// self-hosted Inter: url()s are relative to the stylesheet, so a bundle that inlines fonts.css ships dist/fonts/ beside itself
const fontsCss = `/* GENERATED from tokens.json → fontFaces. Inter © The Inter Project Authors, SIL OFL 1.1 (fonts/OFL.txt). */\n` +
  T.fontFaces.faces.map((f) => `@font-face { font-family: "${f.family}"; src: url("fonts/${f.file}") format("woff2"); font-weight: ${f.weight}; font-style: normal; font-display: swap; unicode-range: ${T.fontFaces.unicodeRange}; }`).join('\n') + '\n';

// before first paint: apply the stored choice to <html>; "system" or nothing stored = no attribute (follow the system, D9), which also
// lifts a dark-only data-theme a page was authored with. Storage may throw (private mode, blocked site data): then the page stays as authored.
const themeInit = `/* empathia theme-init (packages/design-tokens) */(function(){try{var t=localStorage.getItem("${STORAGE_KEY}"),d=document.documentElement;if(t==="light"||t==="dark")d.setAttribute("data-theme",t);else d.removeAttribute("data-theme")}catch(e){}})();\n`;

fs.rmSync(path.join(dist, 'fonts'), { recursive: true, force: true });
fs.mkdirSync(path.join(dist, 'fonts'), { recursive: true });
for (const f of fs.readdirSync(path.join(here, 'fonts')).filter((x) => /\.(woff2|txt)$/.test(x))) fs.copyFileSync(path.join(here, 'fonts', f), path.join(dist, 'fonts', f));
fs.writeFileSync(path.join(dist, 'tokens.css'), css);
fs.writeFileSync(path.join(dist, 'fonts.css'), fontsCss);
fs.writeFileSync(path.join(dist, 'theme-init.js'), themeInit);
const products = own(T.product).map(([id, v]) => ({ id, name: v.name, dark: v.dark, light: v.light }));
fs.writeFileSync(path.join(dist, 'tokens.js'), `// GENERATED from tokens.json\nexport const tokens = ${JSON.stringify(T, null, 1)};\nexport const evidenceStates = ${JSON.stringify(own(T.evidence).map(([k]) => k))};\nexport const productColors = ${JSON.stringify(products, null, 1)};\nexport const THEME_STORAGE_KEY = ${JSON.stringify(STORAGE_KEY)};\nexport const fontPreload = ${JSON.stringify(T.fontFaces.preload)};\n`);
fs.writeFileSync(path.join(dist, 'tokens.d.ts'), `export declare const tokens: Record<string, any>;\nexport declare const evidenceStates: string[];\nexport declare const productColors: { id: string; name: string; dark: string; light: string }[];\nexport declare const THEME_STORAGE_KEY: "${STORAGE_KEY}";\nexport declare const fontPreload: { website: string[]; app: string[] };\n`);
const fontBytes = T.fontFaces.faces.reduce((s, f) => s + fs.statSync(path.join(here, 'fonts', f.file)).size, 0);
console.log(`tokens.css: ${css.length} bytes, ${(css.match(/--/g) || []).length} declarations; fonts: ${T.fontFaces.faces.length} faces, ${fontBytes} bytes; theme-init.js ${themeInit.length} bytes`);
