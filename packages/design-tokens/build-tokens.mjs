#!/usr/bin/env node
/**
 * tokens.json → tokens.css (CSS custom properties) and tokens.ts (typed constants).
 * Theme contract: bare :root = dark (Aurora is dark-first); light under prefers-color-scheme: light unless [data-theme="dark"],
 * and again under [data-theme="light"], so an explicit choice always wins.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const T = JSON.parse(fs.readFileSync(path.join(here, 'tokens.json'), 'utf8'));
const varsFor = (mode) => [
  ...Object.entries(T.color).map(([k, v]) => `  --${k}: ${v[mode]};`),
  ...Object.entries(T.evidence).filter(([k]) => !k.startsWith('$')).map(([k, v]) => `  --ev-${k.toLowerCase().replace(/_/g, '-')}: ${v[mode]};`),
  `  --shadow: ${T.shadow[mode]};`,
  `  color-scheme: ${mode};`,
].join('\n');
const fixed = [
  ...Object.entries(T.font).map(([k, v]) => `  --font-${k}: ${v};`),
  ...Object.entries(T.type).filter(([k]) => !k.startsWith('$')).map(([k, v]) => `  --fs-${k}: ${v};`),
  ...Object.entries(T.space).map(([k, v]) => `  --sp-${k}: ${v};`),
  ...Object.entries(T.radius).map(([k, v]) => `  --r-${k}: ${v};`),
  `  --ease: ${T.motion.ease};`, `  --t-fast: ${T.motion.fast};`, `  --t-med: ${T.motion.med};`,
].join('\n');
const css = `/* GENERATED by packages/design-tokens/build-tokens.mjs from tokens.json — do not edit by hand. */
:root {
${fixed}
${varsFor('dark')}
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
${varsFor('light').replace(/^ {2}/gm, '    ')}
  }
}
:root[data-theme="light"] {
${varsFor('light')}
}
:root[data-theme="dark"] {
${varsFor('dark')}
}
/* Breakpoints (for reference in media queries): ${Object.entries(T.breakpoint).map(([k, v]) => `${k} ${v}`).join(', ')} */
`;
fs.mkdirSync(path.join(here, 'dist'), { recursive: true });
fs.writeFileSync(path.join(here, 'dist', 'tokens.css'), css);
fs.writeFileSync(path.join(here, 'dist', 'tokens.js'), `// GENERATED from tokens.json\nexport const tokens = ${JSON.stringify(T, null, 1)};\nexport const evidenceStates = ${JSON.stringify(Object.keys(T.evidence).filter((k) => !k.startsWith('$')))};\n`);
fs.writeFileSync(path.join(here, 'dist', 'tokens.d.ts'), `export declare const tokens: Record<string, any>;\nexport declare const evidenceStates: string[];\n`);
console.log(`tokens.css: ${css.length} bytes, ${(css.match(/--/g) || []).length} declarations`);
